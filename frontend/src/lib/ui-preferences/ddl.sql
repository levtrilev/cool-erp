-- ════════════════════════════════════════════════════════════════
-- UI PREFERENCES — персональные настройки интерфейса
-- Ядро (core): app/core/user_preferences
-- Источник истины для темы, навигации и состояний таблиц.
-- Браузер хранит только cookie для мгновенной отрисовки.
-- ════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS public.user_ui_preferences (
    user_id     UUID        NOT NULL,
    preferences JSONB       NOT NULL DEFAULT '{}'::jsonb,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- PK = целевой ключ для INSERT ... ON CONFLICT (user_id)
    -- и точка строковой блокировки SELECT ... FOR UPDATE.
    CONSTRAINT pk_user_ui_preferences
        PRIMARY KEY (user_id),

    -- Настройки не живут дольше учётной записи.
    CONSTRAINT fk_user_ui_preferences_user_id
        FOREIGN KEY (user_id)
        REFERENCES public.users (id)
        ON DELETE CASCADE,

    -- Защита только от некорректного типа документа.
    -- Состав ключей НЕ ограничивается: пространства (forms, menus, ...)
    -- добавляются без миграции — в этом смысл JSONB-документа.
    CONSTRAINT chk_user_ui_preferences_is_object
        CHECK (jsonb_typeof(preferences) = 'object')
)
-- Запас свободного места на странице под HOT-обновления:
-- таблица update-heavy, вторичных индексов нет, поэтому обновление
-- документа не порождает новых записей в индексах и не раздувает heap.
WITH (fillfactor = 80);

COMMENT ON TABLE public.user_ui_preferences IS
    'Персональные настройки интерфейса: тема, раскладка навигации, '
    'состояния таблиц (сортировка, фильтры, поиск, пагинация). '
    'Одна строка на пользователя; синхронизация между устройствами '
    'и сохранность после logoff-logon обеспечиваются хранением в БД.';

COMMENT ON COLUMN public.user_ui_preferences.user_id IS
    'Владелец настроек. Изоляция обеспечивается PK + аутентификацией: '
    'доступ всегда по id пользователя из сессии, tenant_id не требуется.';

COMMENT ON COLUMN public.user_ui_preferences.preferences IS
    'Документ настроек: {"theme":{"mode":...},'
    '"navigation":{"layout":...,"sidebar_collapsed":...},'
    '"tables":{"<table_key>":{"column_states":{...},"search":...,'
    '"page":...,"page_size":...}}}. '
    'Валидация структуры и лимитов — на уровне Pydantic-схем модуля.';

COMMENT ON COLUMN public.user_ui_preferences.updated_at IS
    'Момент последнего изменения документа. Поддерживается триггером '
    'независимо от пути записи (ORM или прямой SQL).';


--     Обоснование принятых решений:
-- Одна строка на пользователя, а не KV по каждому пространству. 
-- Сервис сливает патч под SELECT … FOR UPDATE, поэтому конкурентные PATCH из разных 
-- вкладок и устройств сериализуются и не затирают друг друга. 
-- PK даёт и цель для ON CONFLICT (user_id) DO NOTHING при первом сохранении, и точку блокировки.
--
-- tenant_id отсутствует. Настройки адресуются исключительно user_id из сессии — глобально 
-- уникальным ключом. Денормализация tenant_id создала бы риск рассинхронизации при переводе 
-- пользователя в другую организацию и не добавила бы изоляции 
-- (Правило №26 здесь удовлетворяется тем, что запрос всегда ограничен идентификатором 
-- аутентифицированного пользователя).
--
-- version отсутствует. Оптимистическая блокировка для UI-настроек не нужна: 
-- порядок применения обеспечивает строковая блокировка, а последнее значение 
-- по каждому пространству — корректный исход.
--
-- Вторичные индексы не создаются, включая GIN по preferences. Единственный путь чтения — по PK. 
-- GIN и индекс по updated_at ломали бы HOT-обновления и удорожали каждую запись, 
-- которая здесь очень частая. Аналитические запросы вида «кто использует тёмную тему» — редкая 
-- административная задача, для которой последовательное сканирование таблицы размером в 
-- число пользователей приемлемо.
--
-- CHECK ограничивает только тип JSON. Перечень пространств намеренно не фиксируется в БД: 
-- добавление forms, menus и других секций выполняется расширением Pydantic-схем без миграции. 
-- Лимиты (число таблиц, колонок, длина фильтров) контролируются схемами модуля.
-- fillfactor = 80 оставляет 20 % места на странице под новые версии строк — при отсутствии 
-- вторичных индексов обновления остаются HOT и не вызывают разрастание таблицы и индекса PK.